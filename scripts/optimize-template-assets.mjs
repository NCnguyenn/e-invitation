// Re-encode existing artwork only. Next hashes these static imports at build time.
// Run manually after changing originals: node scripts/optimize-template-assets.mjs
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';

// Reuse the image encoder installed with Next; no remote image service is used.
const requireNext = createRequire(import.meta.resolve('next/package.json'));
const sharp = requireNext('sharp');
const folder = 'src/features/template/assets';
await mkdir(folder, { recursive: true });
const widths = {
  'bg-pattern-top.png': 900, 'bg-wave-blue.png': 900,
  'cap-icon.png': 210, 'corner-leaf.png': 480, 'flower-decor.png': 540,
  'spin-badge.png': 240, 'sparkle.png': 255, 'hero-portrait.webp': 870,
  'story-portrait.webp': 870, 'thank-you-banner.webp': 900,
};
const aliases = { 'bg-wave-cream.png': 'bg-pattern-top.png', 'bg-wave-dark.png': 'bg-wave-blue.png' };
const files = (await readdir('images')).filter(file => /\.(png|webp)$/.test(file)).sort();
const imports = [];
const entries = [];
const names = new Map();
let bytes = 0;
for (const file of files) {
  if (aliases[file]) continue;
  const output = file.replace(/\.(png|webp)$/, '.webp');
  const buffer = await sharp(path.join('images', file))
    .rotate()
    .resize({ width: widths[file] ?? 1200, withoutEnlargement: true })
    .webp({ quality: 84, alphaQuality: 100, effort: 6 })
    .toBuffer();
  await writeFile(path.join(folder, output), buffer);
  const variable = `image${imports.length}`;
  names.set(file, variable);
  imports.push(`import ${variable} from './assets/${output}';`);
  entries.push(`  ${JSON.stringify(file)}: ${variable}.src,`);
  bytes += buffer.length;
  console.log(`${file}: ${buffer.length} bytes`);
}
for (const [alias, original] of Object.entries(aliases)) entries.push(`  ${JSON.stringify(alias)}: ${names.get(original)}.src,`);
await writeFile('src/features/template/assets.generated.ts', [
  '// Generated by scripts/optimize-template-assets.mjs. Edit artwork under images/.',
  ...imports, '', 'export const templateAssets: Record<string, string> = {', ...entries, '};', '',
].join('\n'));
console.log(`Optimized bundle: ${bytes} bytes. Original artwork unchanged.`);
